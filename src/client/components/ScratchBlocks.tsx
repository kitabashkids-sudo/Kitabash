import { useMemo } from 'react';
import { renderBlocks, blocksToText } from '../../lib/scratch/blocks.ts';

/** Draws Scratch-style blocks from text (see src/lib/scratch/blocks.ts for the syntax). */
export function ScratchBlocks({ code, scale = 1, className = '', label }: { code: string; scale?: number; className?: string; label?: string }) {
  const r = useMemo(() => renderBlocks(code, { scale, label: label || 'Scratch blocks' }), [code, scale, label]);
  return (
    <figure className={`max-w-full overflow-x-auto ${className}`}>
      {/* Generated by our own renderer from course text; all text is escaped. */}
      <div aria-hidden dangerouslySetInnerHTML={{ __html: r.svg }} style={{ width: r.width, maxWidth: '100%' }} className="[&>svg]:h-auto [&>svg]:max-w-full" />
      <figcaption className="sr-only">
        Blocks: <pre>{blocksToText(code)}</pre>
      </figcaption>
    </figure>
  );
}
