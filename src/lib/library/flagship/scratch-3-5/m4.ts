import { P_ALL, P_IF, broadcast, changeVar, changeX, changeY, eq, forever, goto, hide, ifThen, join, lt, n, onClick, onFlag, onKey, onReceive, project, rand, resetTimer, sayFor, setVar, show, sound, sprite, stopAll, switchBackdrop, timer, gt, touching, vr, waitUntil, ypos } from './lab.ts';

const SPIRAL = { cols: 4, rows: 4, start: { x: 0, y: 0, dir: 'E' as const }, goal: [0, 3] as [number, number], walls: wallsExcept(4, 4, [[0, 0], [1, 0], [2, 0], [3, 0], [3, 1], [3, 2], [3, 3], [2, 3], [1, 3], [0, 3]]) };
const star = (scripts: ReturnType<typeof onFlag>[] = []) => sprite('Star', ['⭐', '🌟'], 0, 0, scripts, { size: 150 });
const catchGame = (withScore: boolean) =>
  project(
    [
      sprite('Bowl', ['🥣'], 0, -150, [onFlag(goto(0, -150), ...(withScore ? [setVar('score', 0)] : [])), onKey('right arrow', changeX(20)), onKey('left arrow', changeX(-20))]),
      sprite('Apple', ['🍎', '🍏'], 0, 170, [
        onFlag(
          goto(0, 170),
          forever(
            changeY(-5),
            ifThen(touching('Bowl'), sound('pop'), ...(withScore ? [changeVar('score', 1)] : []), goto(rand(-220, 220), 170)),
            ifThen(lt(ypos, n(-170)), goto(rand(-220, 220), 170)),
          ),
        ),
      ]),
    ],
    { backdrop: 'grass', vars: withScore ? ['score'] : [] },
  );

